"""Build paper/supplementary.tex from manuscript.tex (statements + proofs) and the generated tables."""
import re, os
os.chdir(os.path.join(os.path.dirname(__file__), ".."))
s = open('manuscript.tex').read()
def block(env, label):
    i = s.index(r"\label{" + label + "}")
    a = s.rfind(r"\begin{" + env + "}", 0, i); b = s.index(r"\end{" + env + "}", i) + len(r"\end{" + env + "}")
    return s[a:b]
strip = lambda t: re.sub(r"\\proofin\{[^}]*\}\n?", "", t)
thm1 = strip(block("theorem", "thm:identity")).replace(r"\begin{theorem}[Three-term identity]", r"\begin{result}[Three-term identity and solvability]").replace(r"\end{theorem}", "")
cor = strip(block("corollary", "cor:ops"))
cb = re.sub(r"\\begin\{corollary\}(\[[^\]]*\])?\\label\{cor:ops\}", "", cor).replace(r"\end{corollary}", "").strip()
thm1 = thm1 + "Moreover, " + cb[0].lower() + cb[1:] + "\n\\end{result}"
thm2 = strip(block("theorem", "thm:spectrum")).replace(r"\begin{theorem}[Spectrum on every grid]", r"\begin{result}[Spectrum on every grid]").replace(r"\end{theorem}", r"\end{result}")
p3 = re.sub(r"\\begin\{proposition\}\\label\{prop:uniform\}", "", strip(block("proposition", "prop:uniform"))).replace(r"\end{proposition}", "").strip()
t4 = re.sub(r"\\begin\{theorem\}\[Fourth-order correction\]\\label\{thm:fourth\}", "", strip(block("theorem", "thm:fourth"))).replace(r"\end{theorem}", "").strip()
res3 = "\\begin{result}[Uniform grids and fourth-order correction]\\label{prop:uniform}\\label{thm:fourth}\n" + p3 + "\nMoreover, " + t4[0].lower() + t4[1:] + "\n\\end{result}"
res4 = strip(block("proposition", "prop:mass")).replace(r"\begin{proposition}[Exact mass conservation]", r"\begin{result}[Exact mass conservation]").replace(r"\end{proposition}", r"\end{result}")
i = s.index(r"\begin{align}", s.index("SAV-BDF2 scheme then reads")); j = s.index(r"\end{align}", i) + len(r"\end{align}")
sav = s[i:j]
res5 = strip(block("theorem", "thm:energy")).replace(r"\begin{theorem}[Solvability, mass, energy]", r"\begin{result}[Solvability, mass and modified-energy decay]").replace(r"\end{theorem}", r"\end{result}")
app = s[s.index(r"\appendix"):s.index(r"\begin{thebibliography}")].replace(r"\appendix", "").replace("%" + "=" * 74, "")
subs = [(r"\\section\{Proofs for Section~\\ref\{sec:method\}\}\\label\{app:ops\}", ""),
        (r"\\section\{Proof of Theorem~\\ref\{thm:energy\}\}\\label\{app:energy\}", r"\\subsection*{Result~5}"),
        (r"\\subsection\{Theorem~\\ref\{thm:identity\} and Corollary~\\ref\{cor:ops\}\}\\label\{app:identity\}", r"\\subsection*{Result~1}"),
        (r"\\subsection\{Theorem~\\ref\{thm:spectrum\}\}\\label\{app:spectrum\}", r"\\subsection*{Result~2}"),
        (r"\\subsection\{Proposition~\\ref\{prop:uniform\}\}\\label\{app:uniform\}", r"\\subsection*{Result~3: symmetry and spectrum}"),
        (r"\\subsection\{Theorem~\\ref\{thm:fourth\}\}\\label\{app:fourth\}", r"\\subsection*{Result~3: fourth-order correction}"),
        (r"\\subsection\{Proposition~\\ref\{prop:mass\}\}\\label\{app:mass\}", r"\\subsection*{Result~4}")]
for a, b in subs: app = re.sub(a, b, app)
num = {"thm:identity": "1", "cor:ops": "1", "thm:spectrum": "2", "prop:uniform": "3", "thm:fourth": "3", "prop:mass": "4", "thm:energy": "5"}
for k, v in num.items():
    app = re.sub(r"\\begin\{proof\}\[Proof of (Theorem|Corollary)~\\ref\{" + k + r"\}\]", r"\\begin{proof}[Proof of Result~" + v + "]", app)
    app = re.sub(r"(Theorem|Corollary|Proposition)~\\ref\{" + k + r"\}", "Result~" + v, app)
left = re.findall(r"\\ref\{(?:thm|cor|prop|app|sec):[^}]*\}", app)
assert not left, left
head = r"""\documentclass[11pt]{article}
\usepackage[textwidth=15cm,textheight=22cm]{geometry}
\usepackage{amsmath,amssymb,amsthm,booktabs,graphicx,array}
\usepackage[colorlinks=true,linkcolor=blue,citecolor=blue,urlcolor=blue]{hyperref}
\setlength{\emergencystretch}{2.5em}
% Use \includeprooffalse when this supplement accompanies the FULL version (its appendix already
% contains the proofs); keep \includeprooftrue for the LEAN version.
\newif\ifincludeproof \includeprooftrue
\newtheorem{result}{Result}
\renewcommand{\thetable}{S\arabic{table}}\renewcommand{\thefigure}{S\arabic{figure}}
\title{Supplementary Material for\\ ``Integrated-Haar wavelet collocation with a provably real spectrum on arbitrary grids''}
\author{Farshid Mossaiby}
\date{}
\begin{document}
\maketitle
\noindent Part~A states the results of the main text formally and proves them. Part~B contains additional
tables and a figure, all generated by the scripts of the repository \url{https://github.com/mossaiby/iHaar}.

\ifincludeproof
\section*{Part A. Statements and proofs}
\subsection*{Notation}
The grid is $a=t_0<t_1<\dots<t_N=b$, with cells $I_k=[t_{k-1},t_k]$ of width $h_k$, midpoints $m_k$ and midpoint
spacings $d_k=(h_k+h_{k+1})/2$. The trial space $\mathcal S_h$ consists of the $C^1$ quadratic splines on the
grid, $U_k=s(m_k)$ are the nodal values, and $c_k=s''|_{I_k}$ are the cell values of the second derivative.
The second-derivative operator is $D_2=A^{-1}L$, and $\delta^2$ is the three-point second-difference matrix.

\subsection*{Statements}
"""
mid = r"""

For the phase-field schemes on a uniform grid, let $K=-\Delta_h$ be the negative of the tensor-sum discrete
Laplacian built from $D_2$ or $D_2^{(4)}$, $\langle v,w\rangle_h=h^d\sum vw$,
$E_{1,h}(u)=\langle\frac14(u^2-1)^2,1\rangle_h$, $f(u)=u^3-u$, $G_h=I$ (Allen--Cahn) or $G_h=K$
(Cahn--Hilliard), $\bar u=2u^n-u^{n-1}$ and $\bar b=f(\bar u)/\sqrt{E_{1,h}(\bar u)+C}$ with $C>0$, and $S\ge0$.
The stabilized SAV-BDF2 scheme is
"""
tabs = [("t_el_nu", "Dependence on Poisson's ratio, prescribed displacements on all edges (smooth solution)."),
        ("t_trac_nu", "Traction on two adjacent edges: dependence on Poisson's ratio."),
        ("t_enh1d", "One-dimensional model $u''=f$ with $u(0)$ and $u'(1)$ given: maximum error with an enhanced end row of weight $\\alpha$."),
        ("t_spectrum", "Spectrum of $D_2$ on random graded grids: largest relative imaginary part of the eigenvalues and largest eigenvector condition number."),
        ("t_resolution", "Planar interface ($\\varepsilon=0.01$): maximum nodal error for three operators."),
        ("t_ch_time", "Cahn--Hilliard: temporal convergence of SAV-BDF2 ($N=128$, $D_2^{(4)}$)."),
        ("t_spinodal", "Spinodal decomposition: conservation, energy and cost."),
        ("t_poisson", "Maximum nodal error and observed convergence rates for two model problems."),
        ("t_el_smooth", "Smooth solution with prescribed displacements on all edges."),
        ("t_trac_smooth", "Traction boundaries, smooth solution: relative $H^1$ error for four configurations, GMRES iterations, and maximum displacement error on the traction edges."),
        ("t_trac_graded", "Traction on two adjacent edges, smooth solution, on graded grids."),
        ("t_el_sing", "Corner singularity with prescribed displacements: uniform versus automatic refinement."),
        ("t_ac", "Allen--Cahn shrinking circle ($\\varepsilon=0.02$, $\\Delta t=0.05$): fitted slope of $R^2(t)$, deviation from $-2\\varepsilon^2$, and the largest step changes of the modified and the original energy."),
        ("t_ch_space", "Cahn--Hilliard: spatial self-convergence in the maximum norm."),
        ("t_compare", "Uniform-grid operators within the identical SAV-BDF2 solver."),
        ("t_fdmstab", "Fast diagonalization (FDM) versus Bartels--Stewart (B--S) for $D_2U+UD_2^{\\mathsf T}=F$ on the worst-conditioned of 20 random graded grids per row.")]
body = "\\clearpage\n\\section*{Part B. Additional tables and figure}\n"
for k, (t, cap) in enumerate(tabs):
    body += "\\begin{table}[htbp]\\centering\\small\n\\caption{" + cap + "}\n\\input{tables/" + t + ".tex}\n\\end{table}\n\n"
    if k % 3 == 2: body += "\\clearpage\n"
tail = r"""\begin{figure}[htbp]\centering
\includegraphics[width=0.62\textwidth]{../figures/cahn_hilliard_3d.pdf}
\caption{Three-dimensional Cahn--Hilliard on $96^3$: slices of the concentration at the final time.}
\end{figure}

\ifincludeproof
\begin{thebibliography}{9}
\bibitem{gantmacher2002oscillation} F.R. Gantmacher, M.G. Krein, Oscillation Matrices and Kernels and Small Vibrations of Mechanical Systems, revised ed., AMS Chelsea Publishing, Providence, RI, 2002.
\bibitem{fallat2011totally} S.M. Fallat, C.R. Johnson, Totally Nonnegative Matrices, Princeton University Press, Princeton, NJ, 2011.
\end{thebibliography}
\fi
\end{document}
"""
out = head + thm1 + "\n\n" + thm2 + "\n\n" + res3 + "\n\n" + res4 + mid + sav + "\n" + res5 + "\n\n\\subsection*{Proofs}\n" + app + "\n\\fi\n\n" + body + tail
extra = "".join("\\begin{table}[htbp]\\centering\\small\n\\caption{" + c + "}\n\\input{tables/" + t + ".tex}\n\\end{table}\n\n" for t, c in [
    ("t_adapt", "Refinement indicator versus a true-error oracle for six configurations."),
    ("t_Ssens", "Sensitivity to the stabilization $S$ and the time step: largest $|u_h|$, error against the reference at $T=2000\\varepsilon^2$, and $\\xi$ at $T$ ($\\varepsilon=0.004$, $384^2$)."),
    ("t_3d", "Three-dimensional manufactured problem $(I-\\Delta)u=f$: maximum nodal error, observed rate and solve time.")])
lean = out.replace("\\begin{figure}[htbp]\\centering", "\\clearpage\n" + extra + "\\begin{figure}[htbp]\\centering", 1)
open("supplementary.tex", "w").write(lean)                                   # lean version: with proofs and S17-S19
open("supplementary_full.tex", "w").write(out.replace(r"\newif\ifincludeproof \includeprooftrue", r"\newif\ifincludeproof \includeprooffalse")
                                          .replace("Part~A states the results of the main text formally and proves them. Part~B contains additional",
                                                   "The proofs are given in the appendices of the main text. Part~B contains additional"))
print("supplementary.tex and supplementary_full.tex written")
