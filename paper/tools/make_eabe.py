def rep(a, b):
    """Replace a passage that must occur exactly once."""
    global out
    assert out.count(a) == 1, (out.count(a), a[:70])
    out = out.replace(a, b)


def cut(start, end, new, include_end=False):
    """Replace the text from `start` up to (excluding, or including) `end` by `new`."""
    global out
    i = out.index(start); j = out.index(end, i) + (len(end) if include_end else 0)
    out = out[:i] + new + out[j:]


def panels(rows, caption, label, width=None):
    s = ["\\begin{figure}[t]\\centering"]
    opt = "[width=" + width + "]" if width else ""
    for row in rows:
        s.append("\\begin{tabular}{@{}" + "c" * len(row) + "@{}}")
        s.append(" & ".join(r"\begin{tabular}{@{}c@{}}\includegraphics" + opt + "{../figures/panels/" + f + ".pdf}" +
                            (r"\\[-1pt]\small " + lab if lab else "") + r"\end{tabular}" for f, lab in row) + "\\\\")
        s.append("\\end{tabular}\\par\\smallskip")
    return "\n".join(s) + "\n\\caption{" + caption + "}\\label{" + label + "}\n\\end{figure}\n"


