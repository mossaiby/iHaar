"""Build paper/supplementary_eabe.tex for the EABE article: Part A (statements and proofs of Results 1-5)
from supplementary.tex, Part B (tables S1-S19 and the 3D figure, numbered as cited in manuscript_eabe.tex)
from supplementary_jsc.tex. Run make_supplement.py and make_supplement_jsc.py first."""
import os
os.chdir(os.path.join(os.path.dirname(__file__), ".."))
lean = open("supplementary.tex").read()
jsc = open("supplementary_jsc.tex").read()
TITLE = ("Fast solvers on arbitrary grids for Haar wavelet collocation: sharp-interface phase-field "
         "computations and adaptive elastostatics")

def part_b(s):
    i = s.index(r"\section*{Part B."); return s.rfind(r"\clearpage", 0, i)
a = lean[:part_b(lean)]
a = a.replace(a[a.index(r"\title{"):a.index("\n", a.index(r"\title{"))],
              r"\title{Supplementary Material for\\ ``" + TITLE + "''}")
a = a.replace(r"all generated by the scripts of the repository \url{https://github.com/mossaiby/iHaar}.",
              r"all generated by the scripts of the repository \url{https://github.com/mossaiby/iHaar} (release v1.1).")
a = a.replace("Part~A states the results of the main text formally and proves them.",
              "Part~A states formally and proves the results used in the main text; Result~2 is Theorem~1 of the "
              "article, and Results~1 and~3--5 are described there informally.")
b = jsc[part_b(jsc):jsc.index(r"\end{document}")]
# tables moved out of the EABE main text (S20 onwards), written by make_eabe.py
b += "\\clearpage\n" + open("tables/eabe_moved.tex").read() + "\n"
k = lean.index(r"\begin{thebibliography}"); bib = lean[lean.rfind(r"\ifincludeproof", 0, k):lean.index(r"\end{document}")]
open("supplementary_eabe.tex", "w").write(a + b + bib + "\\end{document}\n")
print("supplementary_eabe.tex written;", b.count(r"\begin{table}"), "tables")
