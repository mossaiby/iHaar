"""Build paper/supplementary_camwa.tex for the article: Part A (statements and proofs of Results 1-5)
from supplementary.tex (run make_supplement.py first), Part B (tables S1-S19 and the 3D figure), and the
tables moved out of the main text (S20 onwards, written by make_camwa.py)."""
import os, re
os.chdir(os.path.join(os.path.dirname(__file__), ".."))
lean = open("supplementary.tex").read()
TITLE = ("Fast solvers on arbitrary grids for Haar wavelet collocation: sharp-interface phase-field "
         "computations and adaptive elastostatics")

def part_b(s):
    i = s.index(r"\section*{Part B."); return s.rfind(r"\clearpage", 0, i)
a = lean[:part_b(lean)]
a = a.replace(a[a.index(r"\title{"):a.index("\n", a.index(r"\title{"))],
              r"\title{Supplementary Material for\\ ``" + TITLE + "''}")
a = a.replace(r"all generated by the scripts of the repository \url{https://github.com/mossaiby/iHaar}.",
              r"all generated by the scripts of the repository \url{https://github.com/mossaiby/iHaar} (release v1.2).")
a = a.replace("Part~A states the results of the main text formally and proves them.",
              "Part~A states formally and proves the results used in the main text; Result~2 is Theorem~1 of the "
              "article, and Results~1 and~3--5 are described there informally.")
# ---- Part B: additional tables S1-S19 (numbered as cited in the article) and the 3D figure
tabs = [("t_el_nu", "Dependence on Poisson's ratio, prescribed displacements on all edges (smooth solution)."),
        ("t_trac_nu", "Traction on two adjacent edges: dependence on Poisson's ratio."),
        ("t_enh1d", "One-dimensional model $u''=f$ with $u(0)$ and $u'(1)$ given: maximum error with an enhanced end row of weight $\\alpha$."),
        ("t_spectrum", "Spectrum of $D_2$ on random graded grids: largest relative imaginary part of the eigenvalues and largest eigenvector condition number."),
        ("t_resolution", "Planar interface ($\\varepsilon=0.01$): maximum nodal error for three operators."),
        ("t_ch_time", "Cahn--Hilliard: temporal convergence of SAV-BDF2 ($N=128$, $D_2^{(4)}$)."),
        ("t_spinodal", "Spinodal decomposition: conservation, energy and cost."),
        ("t_el_smooth", "Smooth solution with prescribed displacements on all edges."),
        ("t_trac_smooth", "Traction boundaries, smooth solution: relative $H^1$ error for four configurations, GMRES iterations, and maximum displacement error on the traction edges."),
        ("t_trac_graded", "Traction on two adjacent edges, smooth solution, on graded grids."),
        ("t_el_sing", "Corner singularity with prescribed displacements: uniform versus automatic refinement."),
        ("t_ac", "Allen--Cahn shrinking circle ($\\varepsilon=0.02$, $\\Delta t=0.05$): fitted slope of $R^2(t)$, deviation from $-2\\varepsilon^2$, and the largest step changes of the modified and the original energy."),
        ("t_ch_space", "Cahn--Hilliard: spatial self-convergence in the maximum norm."),
        ("t_compare", "Uniform-grid operators within the identical SAV-BDF2 solver."),
        ("t_fdmstab", "Fast diagonalization (FDM) versus Bartels--Stewart (B--S) for $D_2U+UD_2^{\\mathsf T}=F$ on the worst-conditioned of 20 random graded grids per row."),
        ("t_adapt", "Refinement indicator versus a true-error oracle for six configurations."),
        ("t_Ssens", "Sensitivity to the stabilization $S$ and the time step: largest $|u_h|$, error against the reference at $T=2000\\varepsilon^2$, and $\\xi$ at $T$ ($\\varepsilon=0.004$, $384^2$)."),
        ("t_3d", "Three-dimensional manufactured problem $(I-\\Delta)u=f$: maximum nodal error, observed rate and solve time."),
        ("t_fallback", "Cost of the safeguard: fast diagonalization including the backward-error check versus the Bartels--Stewart fallback, on Chebyshev-graded grids (medians of repeated runs).")]
body = "\\clearpage\n\\section*{Part B. Additional tables and figure}\n"
for k, (t, cap) in enumerate(tabs):
    body += "\\begin{table}[htbp]\\centering\\small\n\\caption{" + cap + "}\n\\input{tables/" + t + ".tex}\n\\end{table}\n\n"
    if k % 3 == 2: body += "\\clearpage\n"
import json as _json
_t3 = _json.load(open("../results/ch3d_state.json"))["t"] if os.path.exists("../results/ch3d_state.json") else None
tail = r"""\begin{figure}[htbp]\centering
\begin{tabular}{@{}ccc@{}}
\includegraphics{../figures/panels/ch3d_slice0.pdf} &
\includegraphics{../figures/panels/ch3d_slice1.pdf} &
\includegraphics{../figures/panels/ch3d_slice2.pdf}\\
(a) & (b) & (c)
\end{tabular}
\caption{Three-dimensional Cahn--Hilliard on $96^3$ ($\varepsilon=0.02$, mean concentration 0.1): slices $z=0.26$ (a),
$0.51$ (b) and $0.76$ (c) at $t=""" + ("%.4f" % _t3 if _t3 else "T") + r"""$. The run of Table~S7 was continued with a larger time step
($\Delta t=5\times10^{-5}$, $S=2$) to show the separated phases; no timings are taken from the continuation.}
\end{figure}
\end{document}
"""
b = re.sub(r"(?<![A-Za-z\\])D_([12])", r"\\mathbf D_\1", body + tail[:tail.index(r"\end{document}")])
# tables moved out of the main text (S20 onwards), written by make_camwa.py
b += "\\clearpage\n" + open("tables/camwa_moved.tex").read() + "\n"
k = lean.index(r"\begin{thebibliography}"); bib = lean[lean.rfind(r"\ifincludeproof", 0, k):lean.index(r"\end{document}")]
open("supplementary_camwa.tex", "w").write(a + b + bib + "\\end{document}\n")
print("supplementary_camwa.tex written;", b.count(r"\begin{table}"), "tables")
